void test('emits NO MAXVALUE / NO MINVALUE instead of numeric bounds', () => {
	const columnDefinition = ddlProvider.convertColumnDefinition({
		name: 'id',
		type: 'BIGINT',
		primaryKey: false,
		unique: false,
		nullable: false,
		isActivated: true,
		identity: { generated: 'ALWAYS', noMaxValue: true, noMinValue: true },
	});

	assert.equal(columnDefinition, '"id" BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY (NO MINVALUE, NO MAXVALUE)');
});

void test('emits IMPLICITLY HIDDEN after a ROWID generated clause', () => {
	const columnDefinition = ddlProvider.convertColumnDefinition({
		name: 'row_id',
		type: 'ROWID',
		primaryKey: false,
		unique: false,
		nullable: false,
		generated: 'ALWAYS',
		implicitlyHidden: true,
		isActivated: true,
	});

	assert.equal(columnDefinition, '"row_id" ROWID NOT NULL GENERATED ALWAYS IMPLICITLY HIDDEN');
});

void test('emits IMPLICITLY HIDDEN after an identity clause', () => {
	const columnDefinition = ddlProvider.convertColumnDefinition({
		name: 'id',
		type: 'BIGINT',
		primaryKey: false,
		unique: false,
		nullable: false,
		isActivated: true,
		identity: { generated: 'ALWAYS' },
		implicitlyHidden: true,
	});

	assert.equal(columnDefinition, '"id" BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY IMPLICITLY HIDDEN');
});

void test('does not emit IMPLICITLY HIDDEN for a plain expression-generated column', () => {
	const columnDefinition = ddlProvider.convertColumnDefinition({
		name: 'full_name',
		type: 'VARCHAR',
		length: 100,
		primaryKey: false,
		unique: false,
		nullable: false,
		isActivated: true,
		generatedColumn: true,
		columnGenerationExpression: "first_name || ' ' || last_name",
		implicitlyHidden: true,
	});

	assert.ok(!columnDefinition.includes('IMPLICITLY HIDDEN'));
});
